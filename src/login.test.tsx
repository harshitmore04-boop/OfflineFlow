import {test} from 'node:test';
import assert from 'node:assert/strict';
import {JSDOM} from 'jsdom';
import React,{act} from 'react';
const dom=new JSDOM('<div id="root"></div>',{url:'https://offlineflow.test/'});
Object.assign(globalThis,{window:dom.window,document:dom.window.document,location:dom.window.location,localStorage:dom.window.localStorage,sessionStorage:dom.window.sessionStorage,HTMLElement:dom.window.HTMLElement,IS_REACT_ACT_ENVIRONMENT:true});
Object.defineProperty(globalThis,'navigator',{value:dom.window.navigator,configurable:true});
Object.assign(globalThis,{ResizeObserver:class{observe(){}unobserve(){}disconnect(){}}});
const {createRoot}=await import('react-dom/client');const {default:Login}=await import('./Login');
const root=createRoot(document.getElementById('root')!);
test('legacy demo sessions cannot bypass email OTP, including when configuration is missing',async()=>{
 sessionStorage.setItem('offlineflow-workspace-open','yes');
 sessionStorage.setItem('offlineflow-active-profile',JSON.stringify({name:'Student',email:'student@example.com',phone:''}));
 localStorage.setItem('preserve-document-state','yes');
 await act(async()=>root.render(<Login/>));
 assert.match(document.body.textContent||'',/Sign in with email OTP/);
 assert.doesNotMatch(document.body.textContent||'',/demo|Mobile/i);
 assert.equal(document.querySelector('.logout-link'),null);
 assert.equal(document.querySelector('input[type="password"]'),null);
 assert.ok(document.querySelector<HTMLButtonElement>('button[type="submit"]')!.disabled);
 assert.equal(localStorage.getItem('preserve-document-state'),'yes');
 await act(async()=>root.unmount());
});
